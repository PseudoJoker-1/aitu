#!/usr/bin/env bash
set -euo pipefail

# ============================================================
#  Aitu.kz — One-click deploy script
#  Usage: sudo bash deploy/deploy.sh
# ============================================================

DOMAIN="aituevents.kz"
DEPLOY_USER="deploy"
NODE_MAJOR=20

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

log()   { echo -e "${GREEN}[✔]${NC} $1"; }
warn()  { echo -e "${YELLOW}[!]${NC} $1"; }
err()   { echo -e "${RED}[✘]${NC} $1"; exit 1; }
info()  { echo -e "${CYAN}[→]${NC} $1"; }

# ── Pre-flight checks ──────────────────────────────────────
[[ $EUID -ne 0 ]] && err "Запустите с sudo: sudo bash deploy/deploy.sh"

# Detect project directory (where this script lives → parent)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
BACKEND_DIR="$PROJECT_DIR/backend"

echo ""
echo -e "${CYAN}╔══════════════════════════════════════════════╗${NC}"
echo -e "${CYAN}║       🚀  Aitu.kz Auto-Deploy Script        ║${NC}"
echo -e "${CYAN}╠══════════════════════════════════════════════╣${NC}"
echo -e "${CYAN}║  Domain:  ${YELLOW}$DOMAIN${CYAN}                      ║${NC}"
echo -e "${CYAN}║  Project: ${YELLOW}$PROJECT_DIR${NC}"
echo -e "${CYAN}╚══════════════════════════════════════════════╝${NC}"
echo ""

# ── 1. System packages ─────────────────────────────────────
info "Обновление системы и установка пакетов..."
apt-get update -qq
apt-get install -y -qq python3 python3-venv python3-pip nginx certbot python3-certbot-nginx curl git > /dev/null 2>&1
log "Системные пакеты установлены"

# ── 2. Node.js ──────────────────────────────────────────────
if ! command -v node &> /dev/null || [[ $(node -v | cut -d. -f1 | tr -d 'v') -lt $NODE_MAJOR ]]; then
    info "Установка Node.js $NODE_MAJOR..."
    curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash - > /dev/null 2>&1
    apt-get install -y -qq nodejs > /dev/null 2>&1
    log "Node.js $(node -v) установлен"
else
    log "Node.js $(node -v) уже установлен"
fi

# ── 3. Deploy user ──────────────────────────────────────────
if ! id "$DEPLOY_USER" &>/dev/null; then
    info "Создание пользователя $DEPLOY_USER..."
    adduser --disabled-password --gecos "" "$DEPLOY_USER"
    usermod -aG www-data "$DEPLOY_USER"
    log "Пользователь $DEPLOY_USER создан"
else
    log "Пользователь $DEPLOY_USER уже существует"
fi

# Set ownership of project to deploy user
chown -R "$DEPLOY_USER:www-data" "$PROJECT_DIR"

# ── 4. Green-API credentials (interactive) ──────────────────
echo ""
echo -e "${CYAN}── WhatsApp Green-API credentials ──${NC}"
echo -e "${YELLOW}(нажмите Enter чтобы пропустить, можно настроить позже в $BACKEND_DIR/.env)${NC}"
echo ""

read -rp "GREEN_API_ID_INSTANCE: " GREEN_API_ID
read -rp "GREEN_API_TOKEN: " GREEN_API_TOKEN
read -rp "GREEN_API_PHONE (формат 77001234567): " GREEN_API_PHONE

GREEN_API_ID="${GREEN_API_ID:-}"
GREEN_API_TOKEN="${GREEN_API_TOKEN:-}"
GREEN_API_PHONE="${GREEN_API_PHONE:-}"

# ── 5. Backend setup ────────────────────────────────────────
info "Настройка Django backend..."

# Create venv
if [ ! -d "$BACKEND_DIR/venv" ]; then
    sudo -u "$DEPLOY_USER" python3 -m venv "$BACKEND_DIR/venv"
fi

# Install dependencies
sudo -u "$DEPLOY_USER" "$BACKEND_DIR/venv/bin/pip" install --upgrade pip -q
sudo -u "$DEPLOY_USER" "$BACKEND_DIR/venv/bin/pip" install -r "$BACKEND_DIR/requirements.txt" -q
log "Python зависимости установлены"

# Generate secret key
DJANGO_SECRET_KEY=$("$BACKEND_DIR/venv/bin/python" -c "from django.core.management.utils import get_random_secret_key; print(get_random_secret_key())")

# Create .env
cat > "$BACKEND_DIR/.env" << ENVEOF
# Django Settings (auto-generated by deploy.sh)
DJANGO_SECRET_KEY=$DJANGO_SECRET_KEY
DEBUG=False
ALLOWED_HOSTS=localhost,127.0.0.1,$DOMAIN,www.$DOMAIN
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://127.0.0.1:3000,https://$DOMAIN,https://www.$DOMAIN

# Green-API WhatsApp credentials
GREEN_API_ID_INSTANCE=$GREEN_API_ID
GREEN_API_TOKEN=$GREEN_API_TOKEN
GREEN_API_PHONE=$GREEN_API_PHONE
ENVEOF
chown "$DEPLOY_USER:www-data" "$BACKEND_DIR/.env"
chmod 600 "$BACKEND_DIR/.env"
log ".env создан (SECRET_KEY сгенерирован автоматически)"

# Create logs directory
sudo -u "$DEPLOY_USER" mkdir -p "$BACKEND_DIR/logs"

# Migrate & collectstatic
sudo -u "$DEPLOY_USER" "$BACKEND_DIR/venv/bin/python" "$BACKEND_DIR/manage.py" migrate --noinput
sudo -u "$DEPLOY_USER" "$BACKEND_DIR/venv/bin/python" "$BACKEND_DIR/manage.py" collectstatic --noinput --clear > /dev/null 2>&1
log "Django: миграции и collectstatic выполнены"

# ── 6. Frontend setup ───────────────────────────────────────
info "Сборка Next.js frontend..."

# Create .env.local
cat > "$PROJECT_DIR/.env.local" << ENVEOF
NEXT_PUBLIC_API_URL=https://$DOMAIN
ENVEOF
chown "$DEPLOY_USER:www-data" "$PROJECT_DIR/.env.local"

# npm ci & build
cd "$PROJECT_DIR"
sudo -u "$DEPLOY_USER" npm ci --silent
sudo -u "$DEPLOY_USER" npm run build
log "Next.js собран в standalone mode"

# Copy static files for standalone server
sudo -u "$DEPLOY_USER" cp -r "$PROJECT_DIR/public" "$PROJECT_DIR/.next/standalone/public"
sudo -u "$DEPLOY_USER" cp -r "$PROJECT_DIR/.next/static" "$PROJECT_DIR/.next/standalone/.next/static"
log "Static файлы скопированы для standalone"

# ── 7. Systemd services ────────────────────────────────────
info "Настройка systemd сервисов..."

# Backend service
sed "s|__PROJECT_DIR__|$PROJECT_DIR|g; s|__DEPLOY_USER__|$DEPLOY_USER|g" \
    "$PROJECT_DIR/deploy/aitu-backend.service" > /etc/systemd/system/aitu-backend.service

# Frontend service
sed "s|__PROJECT_DIR__|$PROJECT_DIR|g; s|__DEPLOY_USER__|$DEPLOY_USER|g" \
    "$PROJECT_DIR/deploy/aitu-frontend.service" > /etc/systemd/system/aitu-frontend.service

systemctl daemon-reload
systemctl enable aitu-backend aitu-frontend
systemctl restart aitu-backend
systemctl restart aitu-frontend
log "Systemd сервисы запущены"

# ── 8. Nginx ────────────────────────────────────────────────
info "Настройка Nginx..."

sed "s|__PROJECT_DIR__|$PROJECT_DIR|g" \
    "$PROJECT_DIR/deploy/nginx.conf" > /etc/nginx/sites-available/aitu

ln -sf /etc/nginx/sites-available/aitu /etc/nginx/sites-enabled/aitu
rm -f /etc/nginx/sites-enabled/default

nginx -t
systemctl reload nginx
log "Nginx настроен и запущен"

# ── 9. SSL ──────────────────────────────────────────────────
info "Получение SSL сертификата..."
echo ""
warn "Certbot запросит email для уведомлений о продлении."
echo ""

certbot --nginx -d "$DOMAIN" -d "www.$DOMAIN" --non-interactive --agree-tos --redirect \
    --register-unsafely-without-email 2>/dev/null || {
    warn "SSL не удалось получить (домен может быть не направлен на этот сервер)."
    warn "Запустите позже: sudo certbot --nginx -d $DOMAIN -d www.$DOMAIN"
}

# ── 10. Final check ────────────────────────────────────────
echo ""
echo -e "${CYAN}╔══════════════════════════════════════════════╗${NC}"
echo -e "${CYAN}║            📋  Статус сервисов               ║${NC}"
echo -e "${CYAN}╚══════════════════════════════════════════════╝${NC}"

check_service() {
    if systemctl is-active --quiet "$1"; then
        echo -e "  ${GREEN}●${NC} $1 — ${GREEN}active${NC}"
    else
        echo -e "  ${RED}●${NC} $1 — ${RED}inactive${NC}"
    fi
}

check_service "aitu-backend"
check_service "aitu-frontend"
check_service "nginx"

echo ""
echo -e "${GREEN}╔══════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║          🎉  Деплой завершён!                ║${NC}"
echo -e "${GREEN}╠══════════════════════════════════════════════╣${NC}"
echo -e "${GREEN}║                                              ║${NC}"
echo -e "${GREEN}║  Сайт:   ${CYAN}https://$DOMAIN${GREEN}              ║${NC}"
echo -e "${GREEN}║  Админ:  ${CYAN}https://$DOMAIN/admin/${GREEN}       ║${NC}"
echo -e "${GREEN}║                                              ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════════╝${NC}"
echo ""

# Create superuser prompt
echo -e "${YELLOW}Хотите создать Django суперпользователя? (y/n)${NC}"
read -rp "> " CREATE_SUPER
if [[ "$CREATE_SUPER" =~ ^[Yy]$ ]]; then
    sudo -u "$DEPLOY_USER" "$BACKEND_DIR/venv/bin/python" "$BACKEND_DIR/manage.py" createsuperuser
fi

echo ""
log "Готово! 🚀"
